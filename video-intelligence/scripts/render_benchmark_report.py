#!/usr/bin/env python3
"""Render docs/benchmark-report.md from benchmarks/results/*.json. No numbers are ever typed in.

  python scripts/render_benchmark_report.py

Synthetic results (from the test-double runner) are listed separately and never tabulated as
performance. With no result files the report states plainly that nothing has been measured.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "benchmarks" / "results"
OUT = ROOT / "docs" / "benchmark-report.md"

PLANNED = [
    (
        "yolo-python-baseline",
        "YOLO Python baseline (Ultralytics + ByteTrack)",
        "scripts/benchmark_yolo_baseline.py",
    ),
    ("pipeline-1stream", "DeepStream, 1 stream", "scripts/benchmark_pipeline.py --streams 1"),
    (
        "pipeline-2stream",
        "DeepStream, 2 concurrent streams",
        "scripts/benchmark_pipeline.py --streams 2",
    ),
    (
        "pipeline-4stream",
        "DeepStream, 4 concurrent streams",
        "scripts/benchmark_pipeline.py --streams 4",
    ),
    ("batch-jobs", "Multiple jobs through API + RabbitMQ + worker", "scripts/benchmark_batch.py"),
]


def stat(block: dict | None, key: str = "mean") -> str:
    if not isinstance(block, dict) or key not in block:
        return "n/a"
    return f"{block[key]}"


def load() -> list[dict]:
    docs = []
    for path in sorted(RESULTS.glob("*.json")):
        doc = json.loads(path.read_text())
        doc["_file"] = path.name
        docs.append(doc)
    return docs


def row(doc: dict) -> str:
    r, res, i = doc["results"], doc.get("resources", {}), doc.get("inputs", {})
    host = doc["host"]["hostname"]
    gpu = stat(res.get("gpu_util_pct"))
    if doc["benchmark"] == "batch-jobs":
        return (
            f"| {doc['_file']} | {host} | {r['jobs']} | {r['success_rate']} | "
            f"{r['total_wall_s']} | {r['video_hours_per_wall_hour']} | "
            f"{stat(r['queue_wait_s'], 'p50')} / {stat(r['queue_wait_s'], 'p95')} | "
            f"{gpu} | {stat(res.get('cpu_util_pct'))} | {stat(res.get('mem_used_mib'), 'max')} |"
        )
    ok = r.get("all_streams_reached_eos", "n/a")
    fps = r.get("effective_fps_total")
    probe = i.get("probe", {})
    return (
        f"| {doc['_file']} | {host} | {probe.get('duration_s', 'n/a')} | "
        f"{r['total_frames']} / {r.get('expected_frames_per_stream', r.get('expected_frames'))}"
        f" | {ok} | {r['total_wall_s']} | {fps} | {r['video_hours_per_wall_hour']} | "
        f"{gpu} | {stat(res.get('cpu_util_pct'))} | {stat(res.get('mem_used_mib'), 'max')} |"
    )


STREAM_HEAD = (
    "| result file | host | video s | frames (got / expected per stream) | EOS | wall s |"
    " eff. FPS (total) | video-h per wall-h | GPU util % (mean) | CPU % (mean) |"
    " mem used MiB (max) |\n|---|---|---|---|---|---|---|---|---|---|---|"
)
BATCH_HEAD = (
    "| result file | host | jobs | success rate | wall s | video-h per wall-h |"
    " queue wait p50 / p95 s | GPU util % (mean) | CPU % (mean) |"
    " mem used MiB (max) |\n|---|---|---|---|---|---|---|---|---|---|"
)


def main() -> int:
    docs = load()
    real = [d for d in docs if not d.get("synthetic")]
    synthetic = [d for d in docs if d.get("synthetic")]
    lines = [
        "# Benchmark report",
        "",
        "> Generated by `scripts/render_benchmark_report.py` from `benchmarks/results/*.json`.",
        "> Every number below was measured by the benchmark scripts; none is typed by hand.",
        "> Do not edit this file manually: re-run the benchmarks and re-render it.",
        "",
    ]
    if not real:
        lines += [
            "## Status: NOT MEASURED YET",
            "",
            "No benchmark has been run on the DGX Spark, so this report contains **no performance "
            "numbers**. The authoring environment had no GPU, no DeepStream, no RabbitMQ and no "
            "access to the DGX Spark, and no sample videos or YOLO weights were available.",
            "",
            "Required, in order (see `docs/deployment.md`):",
            "",
        ]
        for _key, title, cmd in PLANNED:
            lines.append(f"- [ ] {title}: `python {cmd}`")
        lines += [
            "- [ ] 1-hour video end to end: `scripts/benchmark_pipeline.py --streams 1` on a "
            "video of at least 3600 s",
            "",
        ]
    else:
        by_kind = {k: [d for d in real if d["benchmark"] == k] for k, _, _ in PLANNED}
        lines += ["## Results", ""]
        for key, title, cmd in PLANNED:
            docs_k = by_kind[key]
            lines += [f"### {title}", ""]
            if not docs_k:
                lines += [f"_Not measured yet._ Run `python {cmd}`.", ""]
                continue
            lines += [BATCH_HEAD if key == "batch-jobs" else STREAM_HEAD]
            lines += [row(d) for d in docs_k]
            lines.append("")
        lines += [
            "## How to read these numbers",
            "",
            "- *video-h per wall-h* = seconds of video completed per second of wall clock.",
            "- *eff. FPS* counts frames received from the pipeline, only meaningful when the run "
            "reached EOS and the frame count matches the expected count.",
            "- GPU memory on GB10 is unified with system RAM and `nvidia-smi` may report it as "
            "N/A; `mem used` is system-wide (includes vLLM and everything else running).",
            "- Resource samples are 1 Hz system-wide, so they include the existing vLLM workloads.",
            "",
        ]
    if synthetic:
        lines += [
            "## Harness self-tests (synthetic runner, NOT performance)",
            "",
            "These files exercised the benchmark scripts with a test double that emits "
            "fake detections. They say nothing about DeepStream or YOLO speed.",
            "",
        ]
        lines += [f"- `{d['_file']}`" for d in synthetic]
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(real)} real result files, {len(synthetic)} synthetic)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
