FIXTURES = Path(__file__).parent / "fixtures"
FAKE_RUNNER = f"{sys.executable} {FIXTURES / 'fake_runner.py'}"
PG_PORT = 54329


def _pg_bin() -> Path | None:
    candidates = sorted(glob.glob("/usr/lib/postgresql/*/bin"))
    return Path(candidates[-1]) if candidates else None


@pytest.fixture(scope="session")
def database_url():
    if url := os.environ.get("TEST_DATABASE_URL"):
        apply_migrations(url)
        yield url
        return

    pg_bin = _pg_bin()
    if pg_bin is None or os.geteuid() != 0:
        pytest.skip("no PostgreSQL available (set TEST_DATABASE_URL)")
    pg_user = pwd.getpwnam("postgres")
    datadir = Path(f"/tmp/vi_pg_{os.getpid()}")
    datadir.mkdir(mode=0o755)
    os.chown(datadir, pg_user.pw_uid, pg_user.pw_gid)

    def as_pg(*cmd: str) -> None:
        subprocess.run(
            ["runuser", "-u", "postgres", "--", *cmd], check=True, capture_output=True, text=True
        )

    as_pg(
        str(pg_bin / "initdb"),
        "-D",
        str(datadir),
        "-A",
        "trust",
        "-U",
        "postgres",
        "-E",
        "UTF8",
        "--locale=C.UTF-8",
    )
    as_pg(
        str(pg_bin / "pg_ctl"),
        "-D",
        str(datadir),
        "-w",
        "-l",
        str(datadir / "log"),
        "-o",
        f"-p {PG_PORT} -k {datadir} -c listen_addresses=127.0.0.1 -c fsync=off",
        "start",
    )
    try:
        with psycopg.connect(
            f"postgresql://postgres@127.0.0.1:{PG_PORT}/postgres", autocommit=True
        ) as conn:
            conn.execute("CREATE DATABASE vi_test ENCODING 'UTF8' TEMPLATE template0")
        url = f"postgresql://postgres@127.0.0.1:{PG_PORT}/vi_test"
        apply_migrations(url)
        yield url
    finally:
        as_pg(str(pg_bin / "pg_ctl"), "-D", str(datadir), "-m", "immediate", "stop")
        shutil.rmtree(datadir, ignore_errors=True)


