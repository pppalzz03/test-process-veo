"""Shared fixtures. Integration tests use a REAL PostgreSQL (no mocks for the database).

Set TEST_DATABASE_URL to use an existing server; otherwise a throwaway cluster is started from
the local PostgreSQL binaries (needs root or the postgres user).
"""

from __future__ import annotations

